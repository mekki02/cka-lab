import { Box, IconButton, Tooltip, Typography, useTheme } from '@mui/material';
import ContentCopyIcon from '@mui/icons-material/ContentCopy';
import CheckIcon from '@mui/icons-material/Check';
import { useEffect, useState, type ReactNode } from 'react';
import { highlight } from './highlighter';

/** Shared frame for every code block: title bar, copy button, scroll, monospace. */
export const codeFrameSx = (dark: boolean) => ({
  position: 'relative' as const,
  my: 2,
  borderRadius: 2,
  border: 1,
  borderColor: 'divider',
  bgcolor: dark ? '#0d1117' : '#f8fafc',
  overflow: 'hidden',
  '& pre': {
    m: 0,
    p: 2,
    pr: 6,
    overflowX: 'auto',
    fontSize: '0.85rem',
    lineHeight: 1.6,
    background: 'transparent !important',
  },
  '& code': { fontSize: 'inherit', bgcolor: 'transparent', p: 0 },
});

export const CopyButton = ({ text }: { text: string }) => {
  const [copied, setCopied] = useState(false);
  const copy = async () => {
    try {
      await navigator.clipboard.writeText(text);
      setCopied(true);
      setTimeout(() => setCopied(false), 1500);
    } catch {
      /* clipboard blocked (http, permissions): nothing sensible to do */
    }
  };
  return (
    <Tooltip title={copied ? 'Copied' : 'Copy'}>
      <IconButton
        size="small"
        onClick={copy}
        aria-label="Copy to clipboard"
        sx={{ position: 'absolute', top: 6, right: 6, bgcolor: 'background.paper', border: 1, borderColor: 'divider', zIndex: 1 }}
      >
        {copied ? <CheckIcon fontSize="small" color="success" /> : <ContentCopyIcon fontSize="small" />}
      </IconButton>
    </Tooltip>
  );
};

export const CodeTitle = ({ children }: { children: ReactNode }) => (
  <Typography
    component="div"
    variant="caption"
    sx={{ px: 2, py: 0.75, borderBottom: 1, borderColor: 'divider', fontFamily: 'monospace', color: 'text.secondary' }}
  >
    {children}
  </Typography>
);

/**
 * Code from API content. Renders plain immediately, then swaps in the
 * highlighted version when the highlighter has loaded.
 */
export const CodeBlock = ({ code, lang, title }: { code: string; lang?: string; title?: string }) => {
  const dark = useTheme().palette.mode === 'dark';
  const [html, setHtml] = useState<string | null>(null);
  const trimmed = code.replace(/\n+$/, '');

  useEffect(() => {
    let alive = true;
    highlight(trimmed, lang)
      .then(h => alive && setHtml(h))
      .catch(() => undefined);
    return () => {
      alive = false;
    };
  }, [trimmed, lang]);

  return (
    <Box sx={codeFrameSx(dark)}>
      {title && <CodeTitle>{title}</CodeTitle>}
      <CopyButton text={trimmed} />
      {html ? (
        // Generated by Shiki from our own content; it escapes the code text.
        <Box dangerouslySetInnerHTML={{ __html: html }} />
      ) : (
        <pre>
          <code>{trimmed}</code>
        </pre>
      )}
    </Box>
  );
};
